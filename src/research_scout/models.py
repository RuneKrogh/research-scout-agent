"""Data models shared by the search tool and the agent."""

from pydantic import BaseModel, Field


class Paper(BaseModel):
    """A research paper as returned by the search tool.

    All metadata, including the citation count, comes from the external source and is
    never generated by the LLM.
    """

    openalex_id: str = Field(description="OpenAlex work URL, e.g. https://openalex.org/W123")
    title: str
    authors: list[str] = Field(default_factory=list)
    year: int | None = None
    citation_count: int | None = None
    doi: str | None = Field(default=None, description="DOI as a https://doi.org/ URL")
    url: str | None = Field(default=None, description="Landing page of the paper")
    abstract: str | None = None

    @property
    def link(self) -> str:
        """Best available link to the paper."""
        return self.doi or self.url or self.openalex_id
